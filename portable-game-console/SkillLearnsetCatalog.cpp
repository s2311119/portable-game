SkillLearnsetCatalog::LearnableSkills SkillLearnsetCatalog::getLearnableSkills(
    int characterId, int oldLevel, int newLevel) {
  LearnableSkills result{};
  for (const SkillLearningRule& rule : learningRules) {
    if (rule.characterId == characterId &&
        rule.level <= newLevel &&
        (rule.level > oldLevel || oldLevel == 0)) {
      if (result.count >= LEARNING_RULE_COUNT) {
        return result;
      }
      result.ids[result.count++] = rule.skillId;
    }
  }
  return result;
}

SkillLearnsetCatalog::InitialSkills SkillLearnsetCatalog::getInitialSkills(int characterId) {
  InitialSkills result{};
  for (const InitialSkillRule& rule : initialSkillRules) {
    if (rule.characterId == characterId) {
      if (result.count >= INITIAL_SKILL_COUNT) {
        return result;
      }
      result.ids[result.count++] = rule.skillId;
    }
  }
  return result;
}
